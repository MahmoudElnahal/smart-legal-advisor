const ai = new GoogleGenAI({ apiKey: process.env.API_KEY || process.env.GEMINI_API_KEY || '' });

// Prioritized model chain to guarantee high availability even during temporary traffic spikes
const CANDIDATE_MODELS = [
  'gemini-3.8-flash',
  'gemini-flash-latest',
  'gemini-3.1-flash-lite'
];

const sleep = (ms: number) => new Promise(resolve => setTimeout(resolve, ms));

/**
 * Executes a Gemini generation request across candidate models with automatic backoff retry.
 * Handles 503 (model high demand / temporary spike) and 429 transparently.
 */
async function executeWithModelFallback(
  contents: any[],
  systemInstruction: string,
  temperature = 0.3
): Promise<string | null> {
  let lastError: any = null;

  for (const modelName of CANDIDATE_MODELS) {
    for (let attempt = 0; attempt < 2; attempt++) {
      try {
        const response: GenerateContentResponse = await ai.models.generateContent({
          model: modelName,
          contents: contents,
          config: {
            systemInstruction,
            temperature,
          },
        });

        if (response && response.text && response.text.trim().length > 0) {
          return response.text.trim();
        }
      } catch (err: any) {
        lastError = err;
        const errMessage = String(err?.message || err || '');
        const isSpikeOrUnavailable = 
          err?.status === 503 ||
          err?.status === 'UNAVAILABLE' ||
          err?.code === 503 ||
          errMessage.includes('503') ||
          errMessage.includes('high demand') ||
          errMessage.includes('UNAVAILABLE') ||
          errMessage.includes('429') ||
          errMessage.includes('quota') ||
          errMessage.includes('RESOURCE_EXHAUSTED') ||
          errMessage.includes('overloaded');

        console.warn(`[Gemini API] Model ${modelName} attempt ${attempt + 1} issue:`, errMessage);

        if (isSpikeOrUnavailable) {
          // Pause before retry or switching model
          await sleep(400 * (attempt + 1));
          continue;
        } else {
          // Non-transient error for this model, switch immediately to next model
          break;
        }
      }
    }
  }

  console.warn('[Gemini API] All remote candidate models exhausted. Activating sovereign legal knowledge synthesizer fallback:', lastError);
  return null;
}

